local accSys = exports["Accounts-System"]
function Interior(hitElement,matchingDimension)
	if (hitElement and getElementType(hitElement) == "player" and not isPedInVehicle(hitElement)) then
		if getElementDimension ( source ) == getElementDimension ( hitElement ) then
			if getElementData(source,"Faction") == 0 then
				local X = getElementData(source, "X")
				local Y = getElementData(source, "Y")
				local Z = getElementData(source, "Z")
				local RotX = getElementData(source, "RotX")
				local RotY = getElementData(source, "RotY")
				local RotZ = getElementData(source, "RotZ")
				local Int = getElementData(source, "Int")
				local Dim = getElementData(source, "Dim")
				SendPlayerLocation( hitElement, X, Y, Z, RotX, RotY, RotZ, Int, Dim)
			else																																			
				if getElementData(accSys:getPlayerAcc(hitElement), "pMember") > 0 and getElementData(accSys:getPlayerAcc(hitElement), "pMember") < 4 or getElementData(source,"Faction") == getElementData(accSys:getPlayerAcc(hitElement), "pMember") then
					local X = getElementData(source, "X")
					local Y = getElementData(source, "Y")
					local Z = getElementData(source, "Z")
					local RotX = getElementData(source, "RotX")
					local RotY = getElementData(source, "RotY")
					local RotZ = getElementData(source, "RotZ")
					local Int = getElementData(source, "Int")
					local Dim = getElementData(source, "Dim")
					SendPlayerLocation( hitElement, X, Y, Z, RotX, RotY, RotZ, Int, Dim)
				else
					OutPutFactionError( hitElement, getElementData(source,"Faction"))
				end
			end
		end
	end
end

function SendPlayerLocation( ThePlayer, X, Y, Z, RotX, RotY, RotZ, Int, Dim)
	triggerClientEvent("EnterSound", ThePlayer, ThePlayer)
	fadeCamera ( ThePlayer, false, 0.4 )  
	setTimer ( FullSend, 700, 1, ThePlayer , X, Y, Z, RotX, RotY, RotZ, Int, Dim) 
end

function FullSend ( ThePlayer, X, Y, Z, RotX, RotY, RotZ, Int, Dim)
	setElementPosition (ThePlayer,  X, Y, Z)
	setElementInterior ( ThePlayer, Int )
	setElementDimension ( ThePlayer, Dim )
	setElementRotation( ThePlayer, RotX, RotY, RotZ, "default", true)
	fadeCamera ( ThePlayer, true, 0.3 )  
end

