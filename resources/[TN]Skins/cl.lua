-- ============================================================================
--  FIX (bugfix pass 3) -- HEADSHOT / HITBOX ON CUSTOM SKINS
--
--  62 skins were loaded with a collision/model id that did not match the id
--  they were replacing, e.g.
--      engineLoadDFF("38.dff", 107)   -- collision taken from model 107
--      engineReplaceModel(dff, 38)    -- but installed as model 38
--
--  The second argument of engineLoadDFF associates the model with a model id
--  for collision/bone purposes. When it disagrees with the id passed to
--  engineReplaceModel, the ped ends up using another skin's skeleton, so
--  per-bodypart hit detection is wrong -- bodypart 9 (head) is never reported
--  and headshots silently do nothing on those skins.
--
--  Every load id is now aligned with the model id being replaced.
-- ============================================================================

