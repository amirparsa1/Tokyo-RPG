function Pistolas ()
for slot = 0, 12 do
local weapon3 = getPedWeapon(source, slot)
if ( weapon3 == 24 ) then
giveWeapon(source, 24, 0, true)
elseif ( weapon3 == 22 ) then
giveWeapon(source, 22, 0, true)
elseif ( weapon3 == 23 ) then
giveWeapon(source, 23, 0, true)
end
end
end
addEvent ("Pistolas", true)
addEventHandler ("Pistolas", root, Pistolas)
